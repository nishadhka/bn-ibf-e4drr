# Save datasets example
def save_datasets(datasets):
    # Save NetCDF datasets
    for name, ds in datasets.items():
        if isinstance(ds, xr.Dataset):
            ds.to_netcdf(f"{dir}/{name}_dataset.nc")
        elif isinstance(ds, pd.DataFrame):
            ds.to_csv(f"{dir}/{name}_dataset.csv", index=False)
        elif isinstance(ds, gpd.GeoDataFrame):
            ds.to_file(f"{dir}/{name}_dataset.geojson", driver="GeoJSON")

